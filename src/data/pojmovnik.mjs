/** Prva rečenica objašnjenja, bez oznaka, za oblačić u članku. */
export function kratko(def) {
  const t = def.replace(/\*/g, '');
  const m = t.match(/^.+?[.!?](?=\s|$)/);
  return (m ? m[0] : t).trim();
}

/** RegExp za prepoznavanje pojma u tekstu (ili null). */
export function regexZa(p) {
  if (!p.oblici) return null;
  return new RegExp(`(?<![\\p{L}\\p{N}])(?:${p.oblici})`, 'iu');
}
